#!/usr/bin/env node

/**
 * AI-Powered Portfolio Data Generator
 * Uses Anthropic Claude API to generate portfolio content
 *
 * Usage:
 *   ANTHROPIC_API_KEY=your_key node scripts/generate-portfolio.js
 *   OR
 *   node scripts/generate-portfolio.js --prompt "Generate portfolio for a full stack developer..."
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import Anthropic from '@anthropic-ai/sdk';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Check for API key
const apiKey = process.env.ANTHROPIC_API_KEY;
if (!apiKey) {
  console.error('❌ Error: ANTHROPIC_API_KEY environment variable not set');
  console.log('\n📝 Setup instructions:');
  console.log('1. Get your free API key from: https://console.anthropic.com/');
  console.log('2. Set it as environment variable:');
  console.log('   - macOS/Linux: export ANTHROPIC_API_KEY="your-key-here"');
  console.log('   - Windows: set ANTHROPIC_API_KEY=your-key-here');
  console.log('3. Run again: node generate-portfolio.js');
  process.exit(1);
}

const anthropic = new Anthropic({ apiKey });

// Parse command line arguments
const args = process.argv.slice(2);
const customPrompt = args.find(arg => !arg.startsWith('--')) || null;
const outputPath = args.includes('--output')
  ? args[args.indexOf('--output') + 1]
  : path.join(__dirname, '..', 'src', 'data', 'portfolioData.js');

// Default prompt if none provided
const defaultPrompt = `
Generate portfolio data for a creative full-stack developer specializing in 3D web experiences.

Return ONLY a valid JSON object with this exact structure:

{
  "personalInfo": {
    "name": "Full Name",
    "title": "Professional Title",
    "subtitle": "Specialization tagline",
    "description": "2-3 sentence professional bio",
    "email": "email@example.com",
    "github": "https://github.com/username",
    "linkedin": "https://linkedin.com/in/username",
    "twitter": "https://twitter.com/username",
    "location": "City, Country",
    "available": true/false
  },
  "skills": [
    {
      "name": "React",
      "icon": "⚛️",
      "color": "#61dafb",
      "level": 95,
      "category": "Frontend"
    }
  ],
  "projects": [
    {
      "id": 1,
      "title": "Project Name",
      "description": "Detailed project description with key features",
      "tech": ["React", "Three.js", "GSAP"],
      "color": "#6c63ff",
      "image": null,
      "live": "https://live-url.com",
      "github": "https://github.com/username/repo",
      "featured": true/false
    }
  ],
  "experience": [
    {
      "id": 1,
      "role": "Job Title",
      "company": "Company Name",
      "period": "2023 — Present",
      "description": "Key responsibilities and achievements",
      "tech": ["React", "Node.js", "MongoDB"],
      "type": "work" // or "education"
    }
  ]
}

Requirements:
- 10 skills with diverse categories (Frontend, Backend, 3D, Animation, etc.)
- 6 projects (2 featured, 4 regular) with realistic tech stacks
- 4 experience entries (3 work + 1 education or mix)
- Use appropriate emojis for skill icons
- Use consistent color scheme (blues, purples, cyans work well)
- Make it realistic and professional
- Period format: "2023 — Present" or "2022 — 2023"
`;

async function generatePortfolioData(prompt) {
  console.log('🤖 Generating portfolio data with Claude...\n');

  try {
    const response = await anthropic.messages.create({
      model: 'claude-3-5-sonnet-20241022',
      max_tokens: 4000,
      temperature: 0.7,
      messages: [
        {
          role: 'user',
          content: prompt
        }
      ]
    });

    const content = response.content[0].text;

    // Extract JSON from response (Claude might add markdown formatting)
    const jsonMatch = content.match(/```(?:json)?\n([\s\S]*?)\n```/)
                    || content.match(/\{[\s\S]*\}/);

    if (!jsonMatch) {
      throw new Error('No valid JSON found in response');
    }

    const jsonStr = jsonMatch[1] || jsonMatch[0];
    const data = JSON.parse(jsonStr);

    console.log('✅ Successfully generated portfolio data!');
    console.log(`   - ${data.personalInfo ? '✓ Personal info' : '✗ Missing personalInfo'}`);
    console.log(`   - ${data.skills?.length || 0} skills`);
    console.log(`   - ${data.projects?.length || 0} projects`);
    console.log(`   - ${data.experience?.length || 0} experience entries`);

    return data;
  } catch (error) {
    console.error('❌ Error generating portfolio data:', error.message);
    if (error.response) {
      console.error('API Response:', error.response.status, error.response.body);
    }
    process.exit(1);
  }
}

function writePortfolioFile(data, outputPath) {
  try {
    const jsContent = `// Portfolio Data - Auto-generated by AI
// Generated: ${new Date().toISOString()}

export const personalInfo = ${JSON.stringify(data.personalInfo, null, 2)};

export const skills = ${JSON.stringify(data.skills, null, 2)};

export const projects = ${JSON.stringify(data.projects, null, 2)};

export const experience = ${JSON.stringify(data.experience, null, 2)};
`;

    // Ensure directory exists
    const dir = path.dirname(outputPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }

    fs.writeFileSync(outputPath, jsContent, 'utf8');
    console.log(`\n📄 Portfolio data written to: ${outputPath}`);
    return true;
  } catch (error) {
    console.error('❌ Error writing file:', error.message);
    return false;
  }
}

async function main() {
  console.log('🚀 Portfolio Data Generator\n');
  console.log('Using prompt:', customPrompt ? 'Custom' : 'Default');

  const prompt = customPrompt || defaultPrompt;
  const data = await generatePortfolioData(prompt);

  if (writePortfolioFile(data, outputPath)) {
    console.log('\n✨ Done! Your portfolio data has been updated.');
    console.log('   Run "npm run dev" to see changes.\n');
  }
}

main().catch(console.error);
